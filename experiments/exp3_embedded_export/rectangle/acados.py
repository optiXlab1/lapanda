def main():
    args = parse_args()
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    teacher_case = build_rectangle_imitation_case(
        args.teacher_margins,
        horizon=args.horizon,
        speed_limit=args.speed_limit,
        steer_limit=args.steer_limit,
    )
    alm_solver, teacher_build_time, teacher_build_rss_delta = build_alm_solver(args)
    teacher_result = solve_alm_once(alm_solver, teacher_case, teacher_case.x0.copy(), False, args)
    teacher_u = np.asarray(teacher_result["solution"], dtype=float)
    np.savetxt(outdir / "teacher_solution.csv", teacher_u, delimiter=",")
    with (outdir / "teacher_summary.json").open("w", encoding="utf-8") as f:
        json.dump(
            {
                "teacher_margins": args.teacher_margins.tolist(),
                "learn_mask": args.learn_mask.tolist(),
                "teacher_build_time_sec": teacher_build_time,
                "teacher_build_rss_delta_mb": teacher_build_rss_delta,
                "teacher_loss_self": 0.0,
                "teacher_metrics": metrics6(teacher_case, teacher_u),
                "teacher_result": {
                    "iterations": int(teacher_result.get("iterations", -1)),
                    "final_residual": float(teacher_result.get("final_residual", np.nan)),
                    "inner_iterations_sum": int(np.sum(np.asarray(teacher_result.get("inner_iterations", []), dtype=int))),
                },
            },
            f,
            indent=2,
        )
    theta0 = build_rectangle_imitation_case(
        args.initial_margins,
        horizon=args.horizon,
        speed_limit=args.speed_limit,
        steer_limit=args.steer_limit,
    ).theta.copy()
    theta0[5:9] = args.initial_margins
    all_rows = []
    if args.backend in {"alm", "both"}:
        rows = train_alm(args, teacher_u, theta0)
        write_rows(outdir / "rectangle_margin_imitation_alm.csv", rows)
        all_rows.extend(rows)
    if args.backend in {"acados", "both"}:
        rows = train_acados(args, teacher_u, theta0)
        write_rows(outdir / "rectangle_margin_imitation_acados.csv", rows)
        all_rows.extend(rows)
    write_rows(outdir / "rectangle_margin_imitation_combined.csv", all_rows)
    summary = {}
    for method in sorted({r["method"] for r in all_rows}):
        rows = [r for r in all_rows if r["method"] == method]
        summary[method] = {
            "initial_loss": rows[0]["loss"],
            "final_loss": rows[-1]["loss"],
            "final_margins": json.loads(rows[-1]["margins"]),
            "mean_forward_time_sec": float(np.mean([r["forward_time_sec"] for r in rows])),
            "mean_backward_time_sec": float(np.mean([r["backward_time_sec"] for r in rows])),
            "statuses": sorted({r.get("status", 0) for r in rows}),
        }
    with (outdir / "summary.json").open("w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
