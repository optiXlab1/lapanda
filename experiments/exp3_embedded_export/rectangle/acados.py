def rss_mb() -> float:
    return psutil.Process(os.getpid()).memory_info().rss / (1024.0 * 1024.0)


def parse_vec(text: str, size: int) -> np.ndarray:
    out = np.asarray([float(x) for x in text.split(",")], dtype=float)
    if out.size != size:
        raise ValueError(f"expected {size} comma-separated values, got {text!r}")
    return out


def write_rows(path: Path, rows: list[dict]):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return
    fieldnames: list[str] = []
    for row in rows:
        for key in row:
            if key not in fieldnames:
                fieldnames.append(key)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def normalized_step(grad: np.ndarray, lr: float) -> np.ndarray:
    norm = float(np.linalg.norm(grad))
    if not np.isfinite(norm) or norm <= 0.0:
        return np.zeros_like(grad)
    return lr * grad / norm


def parse_learn_mask(text: str) -> np.ndarray:
    names = ["left", "right", "bottom", "top"]
    if text.strip().lower() in {"all", "*"}:
        return np.ones(4, dtype=bool)
    selected = {x.strip().lower() for x in text.split(",") if x.strip()}
    unknown = selected.difference(names)
    if unknown:
        raise ValueError(f"unknown margin names in --learn-mask: {sorted(unknown)}")
    return np.asarray([name in selected for name in names], dtype=bool)


def masked_normalized_step(grad: np.ndarray, lr: float, mask: np.ndarray) -> np.ndarray:
    masked = np.asarray(grad, dtype=float).copy()
    masked[~mask] = 0.0
    return normalized_step(masked, lr)


def clip_margins(theta: np.ndarray, margin_bounds: tuple[float, float]) -> np.ndarray:
    out = np.asarray(theta, dtype=float).copy()
    out[5:9] = np.clip(out[5:9], margin_bounds[0], margin_bounds[1])
    return out


def rectangle_case_with_margins(
    margins: np.ndarray,
    horizon: int = 20,
    speed_limit: float = 1.0,
    steer_limit: float = STEER_LIMIT,
):
    case = build_rectangle_imitation_case(
        margins,
        horizon=horizon,
        speed_limit=speed_limit,
        steer_limit=steer_limit,
    )
    theta = case.theta.copy()
    theta[5:9] = np.asarray(margins, dtype=float)
    case.theta = theta
    xmin = -0.35 - theta[5]
    xmax = 0.35 + theta[6]
    ymin = -0.22 - theta[7]
    ymax = 0.22 + theta[8]
    case.meta = {"rectangle": [float(xmin), float(xmax), float(ymin), float(ymax)]}
    return case


def build_rectangle_imitation_case(
    margins: np.ndarray,
    teacher_u: np.ndarray | None = None,
    horizon: int = 20,
    speed_limit: float = 1.0,
    steer_limit: float = STEER_LIMIT,
) -> ObstacleCase:
    dt = 0.12
    n = 2 * horizon
    u = ca.SX.sym("u", n)
    theta = ca.SX.sym("theta", 9)
    variable = ca.SX.sym("variable", 6 + n)
    q_pos, q_heading, r_speed, r_steer, terminal_weight = [theta[i] for i in range(5)]
    margin_left, margin_right, margin_bottom, margin_top = [theta[i] for i in range(5, 9)]
    px, py, heading = variable[0], variable[1], variable[2]
    target_x, target_y, target_heading = variable[3], variable[4], variable[5]
    teacher = variable[6 : 6 + n]
    xmin = -0.35 - margin_left
    xmax = 0.35 + margin_right
    ymin = -0.22 - margin_bottom
    ymax = 0.22 + margin_top
    cost = ca.SX(0)
    constraints = []
    for k in range(horizon):
        speed = u[2 * k]
        steer = u[2 * k + 1]
        px, py, heading = bicycle_step(px, py, heading, speed, steer, dt)
        dx = px - target_x
        dy = py - target_y
        dheading = angle_error(heading, target_heading)
        cost += q_pos * (dx**2 + dy**2)
        cost += q_heading * dheading**2
        cost += r_speed * speed**2 + r_steer * steer**2
        constraints.append(
            0.5
            * ca.fmax(px - xmin, 0) ** 2
            * ca.fmax(xmax - px, 0) ** 2
            * ca.fmax(py - ymin, 0) ** 2
            * ca.fmax(ymax - py, 0) ** 2
        )
    terminal_heading_error = angle_error(heading, target_heading)
    cost += terminal_weight * (q_pos * ((px - target_x) ** 2 + (py - target_y) ** 2) + q_heading * terminal_heading_error**2)
    start = np.array([-1.2, 0.0, 0.0], dtype=float)
    target = np.array([1.2, 0.0, 0.0], dtype=float)
    theta_value = np.array([5.0, 0.2, 1e-2, 1e-2, 20.0, *np.asarray(margins, dtype=float)], dtype=float)
    teacher_value = np.zeros(n, dtype=float) if teacher_u is None else np.asarray(teacher_u, dtype=float)
    variable_value = np.concatenate([start, target, teacher_value])
    problem = CasadiProblem(
        u=u,
        theta=theta,
        variable=variable,
        cost=cost,
        box_lower=np.tile(np.array([-speed_limit, -steer_limit]), horizon),
        box_upper=np.tile(np.array([speed_limit, steer_limit]), horizon),
        constraints=ca.vertcat(*constraints),
        outer_loss=0.5 * ca.sumsqr(u - teacher),
    )
    return ObstacleCase(
        name="rectangle",
        problem=problem,
        horizon=horizon,
        dt=dt,
        theta=theta_value,
        variable=variable_value,
        lower=np.zeros(horizon),
        upper=np.zeros(horizon),
        x0=bicycle_initial_guess(start, target, horizon, dt, y_amp=0.8),
        meta={"rectangle": [-0.35 - theta_value[5], 0.35 + theta_value[6], -0.22 - theta_value[7], 0.22 + theta_value[8]]},
    )


def update_case_theta(case, theta: np.ndarray):
    case.theta = np.asarray(theta, dtype=float).copy()
    xmin = -0.35 - case.theta[5]
    xmax = 0.35 + case.theta[6]
    ymin = -0.22 - case.theta[7]
    ymax = 0.22 + case.theta[8]
    case.meta = {"rectangle": [float(xmin), float(xmax), float(ymin), float(ymax)]}


def metrics6(case, solution):
    view = replace(case, variable=case.variable[:6])
    return metrics(view, solution)


def build_alm_solver(args):
    force_build = args if isinstance(args, bool) else args.force_build
    horizon = 20 if isinstance(args, bool) else args.horizon
    speed_limit = 1.0 if isinstance(args, bool) else args.speed_limit
    steer_limit = STEER_LIMIT if isinstance(args, bool) else args.steer_limit
    case = build_rectangle_imitation_case(
        np.array([0.1, 0.1, 0.1, 0.1]),
        horizon=horizon,
        speed_limit=speed_limit,
        steer_limit=steer_limit,
    )
    solver_name = (
        f"rectangle_margin_imitation_h{horizon}"
        f"_v{str(speed_limit).replace('.', 'p')}"
        f"_s{str(steer_limit).replace('.', 'p')}"
    )
    cache = REPO_ROOT / ".lapanda_cache" / solver_name
    rss_before = rss_mb()
    t0 = time.perf_counter()
    solver = build_solver(
        case.problem,
        backend="compiled",
        name=solver_name,
        cache_dir=cache,
        force=force_build,
        build=True,
    )
    return solver, time.perf_counter() - t0, rss_mb() - rss_before


def alm_options_from_args(args):
    solver_options = SolverOptions()
    solver_options.max_iterations = args.inner_max_iter
    solver_options.tolerance = args.inner_tol
    solver_options.buffer_size = 10
    solver_options.max_stable_iter = args.inner_max_stable_iter

    alm_options = AlmOptions()
    alm_options.max_iterations = args.alm_max_iter
    alm_options.tolerance = args.alm_tol
    alm_options.initial_penalty = args.alm_initial_penalty
    alm_options.penalty_update_factor = args.alm_penalty_update_factor
    alm_options.sufficient_decrease_factor = 0.25
    alm_options.warm_start_inner = True

    backward_options = BackwardOptions()
    backward_options.enable = True
    backward_options.tolerance = args.backward_tol
    backward_options.max_iterations = args.backward_max_iter
    backward_options.constraint_penalty_scale = args.backward_constraint_penalty_scale
    backward_options.constraint_penalty_max = args.backward_constraint_penalty_max
    return solver_options, alm_options, backward_options


def solve_alm_once(solver, case, x0: np.ndarray, enable_backward: bool, args):
    solver_options, alm_options, backward_options = alm_options_from_args(args)
    backward_options.enable = enable_backward
    metadata = solver.generated_oracle.metadata
    return solve_lapanda_compiled(
        str(solver.generated_oracle.library_path),
        metadata["n"],
        metadata["ntheta"],
        metadata["nvar"],
        metadata["ncon"],
        metadata["box_lower"],
        metadata["box_upper"],
        x0,
        case.theta,
        case.variable,
        case.lower,
        case.upper,
        solver_options,
        alm_options,
        backward_options,
        None,
        None,
    )


def train_alm(args, teacher_u: np.ndarray, theta0: np.ndarray):
    solver, build_time, build_rss_delta = build_alm_solver(args)
    theta = theta0.copy()
    case = build_rectangle_imitation_case(
        theta[5:9],
        teacher_u,
        horizon=args.horizon,
        speed_limit=args.speed_limit,
        steer_limit=args.steer_limit,
    )
    solution = case.x0.copy()
    rows = []
    for epoch in range(args.epochs + 1):
        update_case_theta(case, theta)
        x0 = case.x0.copy() if args.no_warm_start else solution
        rss_before_solve = rss_mb()
        result = solve_alm_once(solver, case, x0, True, args)
        solve_rss_delta = rss_mb() - rss_before_solve
        solution = np.asarray(result["solution"], dtype=float)
        grad_full = np.asarray(result.get("grad_theta", np.zeros_like(theta)), dtype=float)
        grad = grad_full[5:9]
        loss = 0.5 * float(np.sum((solution - teacher_u) ** 2))
        forward_time = float(result["forward_time_sec"])
        backward_time = float(result["backward_time_sec"])
        row = {
            "method": "lapanda_c",
            "epoch": epoch,
            "loss": loss,
            "forward_time_sec": forward_time,
            "backward_time_sec": backward_time,
            "total_time_sec": forward_time + backward_time,
            "outer_iterations": int(result.get("outer_iterations", result.get("iterations", -1))),
            "inner_iterations_sum": int(np.sum(np.asarray(result.get("inner_iterations", []), dtype=int))),
            "backward_iterations": int(result.get("backward_iterations", -1)),
            "final_residual": float(result.get("final_residual", np.nan)),
            "grad_norm": float(np.linalg.norm(grad)),
            "margins": json.dumps(theta[5:9].tolist()),
            "teacher_margins": json.dumps(args.teacher_margins.tolist()),
            "build_time_sec": build_time,
            "build_rss_delta_mb": build_rss_delta,
            "solve_rss_delta_mb": solve_rss_delta,
            **metrics6(case, solution),
        }
        rows.append(row)
        print(f"ALM epoch={epoch:03d} loss={loss:.6e} margins={theta[5:9]} grad_norm={row['grad_norm']:.3e}")
        if epoch < args.epochs:
            step = masked_normalized_step(grad, args.lr, args.learn_mask)
            if args.line_search:
                best_theta = theta.copy()
                best_loss = loss
                best_solution = solution
                for scale in args.line_search_scales:
                    candidate = theta.copy()
                    candidate[5:9] -= scale * step
                    candidate = clip_margins(candidate, args.margin_bounds)
                    update_case_theta(case, candidate)
                    candidate_result = solve_alm_once(solver, case, solution, False, args)
                    candidate_solution = np.asarray(candidate_result["solution"], dtype=float)
                    candidate_loss = 0.5 * float(np.sum((candidate_solution - teacher_u) ** 2))
                    if candidate_loss <= best_loss:
                        best_theta = candidate
                        best_loss = candidate_loss
                        best_solution = candidate_solution
                        break
                theta = best_theta
                solution = best_solution
            else:
                theta[5:9] -= step
                theta = clip_margins(theta, args.margin_bounds)
    return rows


def acados_p(theta: np.ndarray, variable: np.ndarray) -> np.ndarray:
    return np.r_[theta, variable[:6]]


def rollout_controls_as_states(u: np.ndarray, variable: np.ndarray, horizon: int, dt: float) -> np.ndarray:
    px, py, psi = variable[:3]
    states = []
    for k in range(horizon):
        v = float(u[2 * k])
        steer = float(u[2 * k + 1])
        px = px + dt * v * np.cos(psi)
        py = py + dt * v * np.sin(psi)
        psi = psi + dt * v * np.tan(steer) / WHEELBASE
        states.append([float(px), float(py), float(psi)])
    return np.asarray(states, dtype=float)


def build_acados_ocp(case, name: str, outdir: Path, sensitivity: bool, args):
    from acados_template import AcadosModel, AcadosOcp

    nx, nu = 3, 2
    model = AcadosModel()
    model.name = name
    x = ca.SX.sym("x", nx)
    u = ca.SX.sym("u", nu)
    p = ca.SX.sym("p_global", 15)
    px, py, heading = x[0], x[1], x[2]
    speed, steer = u[0], u[1]
    q_pos, q_heading, r_speed, r_steer, terminal_weight = [p[i] for i in range(5)]
    margin_left, margin_right, margin_bottom, margin_top = [p[i] for i in range(5, 9)]
    start_target_offset = 9
    target_x, target_y, target_heading = p[start_target_offset + 3], p[start_target_offset + 4], p[start_target_offset + 5]
    xmin = -0.35 - margin_left
    xmax = 0.35 + margin_right
    ymin = -0.22 - margin_bottom
    ymax = 0.22 + margin_top
    px_next = px + case.dt * speed * ca.cos(heading)
    py_next = py + case.dt * speed * ca.sin(heading)
    model.x = x
    model.u = u
    model.p_global = p
    model.disc_dyn_expr = ca.vertcat(
        px_next,
        py_next,
        heading + case.dt * speed * ca.tan(steer) / WHEELBASE,
    )
    dx = px - target_x
    dy = py - target_y
    dheading = ca.atan2(ca.sin(heading - target_heading), ca.cos(heading - target_heading))
    use_external = sensitivity or args.acados_forward_mode == "exact"
    if use_external:
        model.cost_expr_ext_cost = q_pos * (dx**2 + dy**2) + q_heading * dheading**2 + r_speed * speed**2 + r_steer * steer**2
        model.cost_expr_ext_cost_e = terminal_weight * (q_pos * (dx**2 + dy**2) + q_heading * dheading**2)
    else:
        model.cost_y_expr = ca.vertcat(
            ca.sqrt(q_pos) * dx,
            ca.sqrt(q_pos) * dy,
            ca.sqrt(q_heading) * dheading,
            ca.sqrt(r_speed) * speed,
            ca.sqrt(r_steer) * steer,
        )
        model.cost_y_expr_e = ca.vertcat(
            ca.sqrt(terminal_weight * q_pos) * dx,
            ca.sqrt(terminal_weight * q_pos) * dy,
            ca.sqrt(terminal_weight * q_heading) * dheading,
        )
    model.con_h_expr = ca.vertcat(
        0.5
        * ca.fmax(px_next - xmin, 0) ** args.constraint_power
        * ca.fmax(xmax - px_next, 0) ** args.constraint_power
        * ca.fmax(py_next - ymin, 0) ** args.constraint_power
        * ca.fmax(ymax - py_next, 0) ** args.constraint_power
    )

    ocp = AcadosOcp()
    ocp.model = model
    ocp.solver_options.N_horizon = case.horizon
    ocp.solver_options.tf = case.horizon * case.dt
    ocp.solver_options.integrator_type = "DISCRETE"
    ocp.solver_options.nlp_solver_type = "SQP"
    ocp.solver_options.nlp_solver_max_iter = args.acados_max_iter
    ocp.solver_options.nlp_solver_tol_stat = args.acados_tol
    ocp.solver_options.nlp_solver_tol_eq = args.acados_tol
    ocp.solver_options.nlp_solver_tol_ineq = args.acados_tol
    ocp.solver_options.nlp_solver_tol_comp = args.acados_tol
    ocp.solver_options.qp_solver = "PARTIAL_CONDENSING_HPIPM"
    ocp.solver_options.qp_solver_cond_N = case.horizon
    ocp.solver_options.qp_solver_ric_alg = 0
    ocp.solver_options.qp_solver_cond_ric_alg = 0
    ocp.solver_options.hessian_approx = "EXACT" if use_external else "GAUSS_NEWTON"
    ocp.solver_options.globalization = "MERIT_BACKTRACKING"
    ocp.solver_options.regularize_method = "NO_REGULARIZE" if sensitivity else args.acados_regularize
    if sensitivity:
        ocp.solver_options.with_solution_sens_wrt_params = True
        ocp.solver_options.with_value_sens_wrt_params = True
    if use_external:
        ocp.cost.cost_type = "EXTERNAL"
        ocp.cost.cost_type_e = "EXTERNAL"
    else:
        ocp.cost.cost_type = "NONLINEAR_LS"
        ocp.cost.cost_type_e = "NONLINEAR_LS"
        ocp.cost.W = 2.0 * np.eye(5)
        ocp.cost.W_e = 2.0 * np.eye(3)
        ocp.cost.yref = np.zeros(5)
        ocp.cost.yref_e = np.zeros(3)
    ocp.constraints.x0 = case.variable[:3]
    ocp.constraints.lbu = np.array([float(case.problem.box_lower[0]), float(case.problem.box_lower[1])])
    ocp.constraints.ubu = np.array([float(case.problem.box_upper[0]), float(case.problem.box_upper[1])])
    ocp.constraints.idxbu = np.array([0, 1])
    ocp.constraints.lh = np.array([0.0])
    ocp.constraints.uh = np.array([0.0])
    ocp.p_global_values = acados_p(case.theta, case.variable)
    ocp.code_export_directory = str(outdir / f"acados_codegen_{name}")
    return ocp


def build_acados_solvers(case, outdir: Path, args):
    from acados_template import AcadosOcpSolver

    forward_ocp = build_acados_ocp(case, "rect_margin_forward", outdir, False, args)
    forward_solver = AcadosOcpSolver(forward_ocp, json_file=str(outdir / "acados_forward_ocp.json"), verbose=False)
    sens_ocp = build_acados_ocp(case, "rect_margin_sensitivity", outdir, True, args)
    sensitivity_solver = AcadosOcpSolver(sens_ocp, json_file=str(outdir / "acados_sensitivity_ocp.json"), verbose=False)
    return forward_solver, sensitivity_solver


def acados_set_guess(solver, u_guess: np.ndarray, case):
    states = np.vstack([case.variable[:3], rollout_controls_as_states(u_guess, case.variable, case.horizon, case.dt)])
    for k in range(case.horizon + 1):
        solver.set(k, "x", states[k])
    for k in range(case.horizon):
        solver.set(k, "u", u_guess[2 * k : 2 * k + 2])


def acados_get_u(solver, horizon: int) -> np.ndarray:
    out = np.zeros(2 * horizon)
    for k in range(horizon):
        out[2 * k : 2 * k + 2] = solver.get(k, "u")
    return out


def get_iterate_obj(solver):
    if hasattr(solver, "get_flat_iterate"):
        return solver.get_flat_iterate()
    return solver.store_iterate_to_flat_obj()


def train_acados(args, teacher_u: np.ndarray, theta0: np.ndarray):
    case = rectangle_case_with_margins(
        theta0[5:9],
        horizon=args.horizon,
        speed_limit=args.speed_limit,
        steer_limit=args.steer_limit,
    )
    tmp_root = Path(tempfile.mkdtemp(prefix="rect_margin_acados_", dir=str(args.outdir)))
    rss_before_build = rss_mb()
    t0 = time.perf_counter()
    forward_solver, sensitivity_solver = build_acados_solvers(case, tmp_root, args)
    build_time = time.perf_counter() - t0
    build_rss_delta = rss_mb() - rss_before_build
    theta = theta0.copy()
    u_guess = case.x0.copy()
    rows = []
    for epoch in range(args.epochs + 1):
        update_case_theta(case, theta)
        p_global = acados_p(theta, case.variable)
        for solver in [forward_solver, sensitivity_solver]:
            solver.set_p_global_and_precompute_dependencies(p_global)
        guess = case.x0.copy() if args.no_warm_start else u_guess
        acados_set_guess(forward_solver, guess, case)
        rss_before_solve = rss_mb()
        t0 = time.perf_counter()
        status = forward_solver.solve()
        forward_time = time.perf_counter() - t0
        u_sol = acados_get_u(forward_solver, case.horizon)
        residual = u_sol - teacher_u
        loss = 0.5 * float(np.sum(residual**2))
        seeds_u = [(k, residual[2 * k : 2 * k + 2].reshape(2, 1)) for k in range(case.horizon)]
        t1 = time.perf_counter()
        try:
            sensitivity_solver.load_iterate_from_flat_obj(get_iterate_obj(forward_solver))
            sensitivity_solver.setup_qp_matrices_and_factorize()
            sens = sensitivity_solver.eval_adjoint_solution_sensitivity(
                seed_x=None,
                seed_u=seeds_u,
                with_respect_to="p_global",
                sanity_checks=False,
            )
            grad_full = np.asarray(sens, dtype=float).reshape(-1)[:9]
            backward_status = "ok"
        except Exception as exc:
            grad_full = np.zeros(9, dtype=float)
            backward_status = repr(exc)
        backward_time = time.perf_counter() - t1
        solve_rss_delta = rss_mb() - rss_before_solve
        grad = grad_full[5:9]
        try:
            stat = np.asarray(forward_solver.get_stats("statistics"), dtype=float)
            sqp_iterations = int(stat[0, -1]) if stat.ndim == 2 and stat.shape[1] else -1
            last_qp_status = int(stat[5, -1]) if stat.ndim == 2 and stat.shape[0] > 5 else -1
        except Exception:
            sqp_iterations = -1
            last_qp_status = -1
        rows.append(
            {
                "method": "acados",
                "epoch": epoch,
                "loss": loss,
                "forward_time_sec": forward_time,
                "backward_time_sec": backward_time,
                "total_time_sec": forward_time + backward_time,
                "status": int(status),
                "backward_status": backward_status,
                "sqp_iterations": sqp_iterations,
                "last_qp_status": last_qp_status,
                "grad_norm": float(np.linalg.norm(grad)),
                "margins": json.dumps(theta[5:9].tolist()),
                "teacher_margins": json.dumps(args.teacher_margins.tolist()),
                "build_time_sec": build_time,
                "build_rss_delta_mb": build_rss_delta,
                "solve_rss_delta_mb": solve_rss_delta,
                **metrics(case, u_sol),
            }
        )
        print(f"acados epoch={epoch:03d} status={status} loss={loss:.6e} margins={theta[5:9]} grad_norm={np.linalg.norm(grad):.3e}")
        u_guess = u_sol
        if epoch < args.epochs and status == 0:
            theta[5:9] -= masked_normalized_step(grad, args.lr, args.learn_mask)
            theta = clip_margins(theta, args.margin_bounds)
    if not args.keep_acados_code:
        shutil.rmtree(tmp_root, ignore_errors=True)
    return rows


